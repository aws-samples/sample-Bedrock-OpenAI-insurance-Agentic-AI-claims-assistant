def _https_urlopen(req, timeout):
    """
    urlopen, but only over HTTPS.

    urllib will happily open file:// and other schemes; this refuses anything
    that is not HTTPS before the request goes out, so a malformed or tampered
    URL cannot turn into a local-file read or an SSRF onto an unexpected scheme.
    """
    url = req.full_url if hasattr(req, "full_url") else str(req)
    if not url.lower().startswith("https://"):
        raise ValueError(f"refusing non-https request URL: {url!r}")
    return urllib.request.urlopen(req, timeout=timeout)  # nosec B310 - https asserted above  # nosemgrep: python.lang.security.audit.dynamic-urllib-use-detected.dynamic-urllib-use-detected


# Token-shaped strings we refuse to let into CloudWatch, even second-hand.
_TOKEN_SHAPES = re.compile(
    r"(sk-[A-Za-z0-9_\-]{8,}"          # OpenAI-style API key
    r"|ek_[A-Za-z0-9_\-]{8,}"          # OpenAI-style ephemeral key
    r"|Bearer\s+[A-Za-z0-9._\-]{8,}"   # Authorization header value
    r"|eyJ[A-Za-z0-9._\-]{16,})",      # JWT
    re.IGNORECASE,
)


def _safe_upstream_detail(body: bytes | str, limit: int = 400) -> str:
    """
    Make a third-party error body safe to log.

    An upstream error body is useful for debugging but is not ours, so we do not
    trust its contents: a proxy or gateway in front of the provider can echo
    request material back in a failure response. Anything token-shaped is
    replaced before the string reaches the log, and the result is truncated.
    """
    text = body.decode(errors="replace") if isinstance(body, bytes) else str(body)
    return _TOKEN_SHAPES.sub("[redacted]", text)[:limit]


