"""
BFSI Assistant API — Session_Broker + Tool_Broker in one function.

Routes
  POST /session       validate JWT, create Session_Record, mint an OpenAI ephemeral key
  POST /mcp           MCP JSON-RPC: initialize, tools/list, tools/call
  POST /audit-verify  recompute the caller's own audit chain

Trust rule: the client is untrusted. Identity, assurance, eligibility, and
account scope are read from the Session_Record only.

Responsible AI (full detail in RESPONSIBLE-AI.md at the repository root)
  Assist, don't decide  — every AI surface here is advisory. No model can settle a
    claim, approve a payout, move money, or change an account: the tool registry
    contains no such tool and `authorization_policy.json` is deny-by-default, so
    the limit is architectural rather than a prompt instruction.
  Human-in-the-loop    — mandatory for anything consequential. Settlement or
    amount requests escalate to a specialist, high-risk actions demand step-up
    verification, and a claims recommendation only takes effect once a named
    specialist records a decision on it.
  Disclosure           — DISCLOSURE below is injected into the model's session
    instructions and surfaced in the UI, alongside a persistent on-page banner. It
    tells the customer the guidance is AI-generated, is not financial, legal, or
    insurance advice, and should be reviewed by a colleague before it is acted on.
  Guardrails           — the claims-review path runs on Amazon Bedrock behind a
    Bedrock guardrail and fails closed without one (see claims.py). The voice path
    is browser-to-OpenAI over WebRTC, so its audio never reaches AWS and a Bedrock
    guardrail cannot apply; what compensates is that the model holds no authority,
    no tool returns a monetary figure, and money is computed by deterministic code.
  Fairness             — synthetic fixtures only, so no fairness claim is made.
    RESPONSIBLE-AI.md names the parity and robustness testing an adopter owes
    before launch, including protected and vulnerable groups.
"""
