def _plain(item):
    """Decimal → int/float, drop table keys."""
    def conv(v):
        if isinstance(v, Decimal):
            return int(v) if v == v.to_integral_value() else float(v)
        if isinstance(v, dict):
            return {k: conv(x) for k, x in v.items()}
        if isinstance(v, list):
            return [conv(x) for x in v]
        return v
    return {k: conv(v) for k, v in (item or {}).items() if k not in ("pk", "sk", "ttl")}


def handle_session_trace(event):
    """
    Operator view data. Everything here is read from the server's own records:
    the evidence trace, the audit chain, and the session state. Nothing is taken
    from the client.
    """
    claims = _claims(event)
    sub = claims.get("sub")
    username = claims.get("cognito:username") or claims.get("username")
    if not sub or not username:
        return _resp(401, {"error": "authentication required"})

    body = json.loads(event.get("body") or "{}")
    session_id = body.get("session_id")

    sessions = [
        {"session_id": s["session_id"], "created_at": int(s.get("created_at", 0)),
         "assurance_level": s.get("assurance_level"),
         "geography": s.get("geography"),
         "eligible_classifications": list(s.get("eligible_classifications") or [])}
        for s in store.sessions_for_customer(username)
    ]

    if not session_id:
        return _resp(200, {"sessions": sessions, "session_id": None})

    session = store.get_session(session_id)
    if not session or session.get("cognito_sub") != sub:
        return _resp(403, {"error": "not your session"})

    trace = store.get_evidence_trace(session_id)
    context = audit.session_context(session_id)
    chain = audit.verify(session_id)

    return _resp(200, {
        "sessions": sessions,
        "session_id": session_id,
        "session": {
            "customer_id": session.get("customer_id"),
            "assurance_level": policy.effective_assurance(session),
            "geography": session.get("geography"),
            "eligible_classifications": list(session.get("eligible_classifications") or []),
            "accounts": list(session.get("accounts") or []),
            "created_at": int(session.get("created_at", 0)),
        },
        "evidence": [_plain(t) for t in trace],
        "tools": context["tool_history"],
        "denials": context["denials"],
        "documents_cited": context["documents_cited"],
        "audit": {"entries": context["audit_entries"], **chain},
        "policy_version": policy.VERSION,
    })


