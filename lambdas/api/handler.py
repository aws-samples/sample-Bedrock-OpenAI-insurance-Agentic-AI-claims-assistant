# Provider Voice Assistant — the Realtime surface over the same claim.
#
# A second OpenAI interaction surface on the claims demo, deliberately kept off
# the /mcp broker so the BFSI advisor's tool set and authorization policy are
# untouched. Same Realtime + WebRTC pattern as /session, different instructions,
# different tools, and no path to a settlement outcome.
#
#   POST /claim-voice-session   mint an ephemeral Realtime credential
#   POST /claim-voice-tool      broker one claims-voice tool call
#   POST /claim-voice-event     client telemetry (first audio, interruption, end)
# ══════════════════════════════════════════════════════════════════════
def handle_claim_voice_session(event):
    """
    Mint a short-lived Realtime credential for the provider voice assistant.

    The long-lived OpenAI key never leaves this function. The browser receives
    only the ephemeral secret and a session id it must present on every tool
    call, and that session id is bound to this caller's Cognito subject.
    """
    claims = _claims(event)
    sub = claims.get("sub")
    username = claims.get("cognito:username") or claims.get("username")
    if not sub or not username:
        return _resp(401, {"error": "authentication required"})

    customer = store.get_customer(username)
    if not customer:
        return _resp(403, {"error": "no customer record for this sign-in"})

    # Reuse the existing Session_Record so the tool route gets session binding,
    # expiry and identity resolution for free rather than reinventing them.
    session = store.create_session(customer, sub)

    payload = {
        "expires_after": {"anchor": "created_at", "seconds": claims_voice.EPHEMERAL_TTL},
        "session": claims_voice.session_config(),
    }
    req = urllib.request.Request(
        f"{OPENAI_BASE}/realtime/client_secrets",
        data=json.dumps(payload).encode(),
        headers={"Authorization": f"Bearer {_openai_key()}",
                 "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with _https_urlopen(req, timeout=15) as r:
            minted = json.loads(r.read())
    except urllib.error.HTTPError as exc:
        detail = _safe_upstream_detail(exc.read())
        log.error("realtime voice session mint rejected upstream: status=%s detail=%s",
                  exc.code, detail)
        return _resp(502, {"error": "could not start a voice session",
                           "upstream_status": exc.code})
    except Exception:  # noqa: BLE001
        log.exception("realtime voice session mint failed")
        return _resp(502, {"error": "could not start a voice session"})

    audit.append(
        f"CLAIMVOICE#{session['session_id']}",
        request_id=event["requestContext"]["requestId"],
        customer_id=customer["customer_id"],
        action="voice.session_create", decision="allow",
        reason="provider voice assistant session established",
        policy_version=policy.VERSION, result_status="ok",
    )
    log.info(json.dumps({
        "event": "claim_voice_session_started",
        "session_id": session["session_id"], "customer_id": customer["customer_id"],
        "model": claims_voice.MODEL, "ttl_seconds": claims_voice.EPHEMERAL_TTL,
    }))

    # Only the ephemeral credential and what the page needs to render. No API
    # key, no instructions, no tool internals.
    return _resp(200, {
        "session_id": session["session_id"],
        "client_secret": minted.get("value"),
        "expires_at": minted.get("expires_at"),
        "model": claims_voice.MODEL,
        "claim": claims_voice.claim_summary(),
        # The opening line, so the page can show what the caller is about to
        # hear rather than keeping its own copy that drifts.
        "greeting": claims_voice.GREETING,
        "authority": {
            "may": ["retrieve claim status", "explain outstanding documents",
                    "explain policy deductions", "request outstanding documents",
                    "hand off to a specialist"],
            "may_not": ["approve a claim", "reject a claim", "settle a claim",
                        "state a settlement amount"],
            "note": "Inform and retrieve only. No settlement authority.",
        },
    })


def handle_claim_voice_tool(event):
    """
    Broker one claims-voice tool call.

    The model's arguments are untrusted input. Identity comes from the JWT and
    the Session_Record, never from the arguments. Only the five tools in the
    claims_voice registry are reachable; there is no approve or settle entry.
    """
    claims = _claims(event)
    sub = claims.get("sub")
    if not sub:
        return _resp(401, {"error": "authentication required"})

    try:
        body = json.loads(event.get("body") or "{}")
    except json.JSONDecodeError:
        return _resp(400, {"error": "malformed request"})

    headers = {k.lower(): v for k, v in (event.get("headers") or {}).items()}
    session_id = headers.get("x-session-id") or body.get("session_id")
    if not session_id:
        return _resp(400, {"error": "x-session-id header required"})

    session = store.get_session(session_id)
    if not session:
        return _resp(400, {"error": "session not found or expired"})
    if session.get("cognito_sub") != sub:
        log.warning("voice session binding mismatch session=%s", session_id)
        audit.append(
            f"CLAIMVOICE#{session_id}",
            request_id=event["requestContext"]["requestId"],
            customer_id=session.get("customer_id"),
            action="voice.session_binding_mismatch", decision="deny",
            reason="session presented by a different identity",
            policy_version=policy.VERSION, result_status="blocked",
        )
        return _resp(403, {"error": "session does not belong to this identity"})

    name = body.get("name")
    args = body.get("arguments") or {}
    request_id = event["requestContext"]["requestId"]

    # An attempt to reach a settlement route through this surface is a security
    # event, not a typo. Recorded as one.
    if name in claims_voice.FORBIDDEN_TOOLS:
        log.warning("voice attempted forbidden tool %s", name)
        audit.append(
            f"CLAIMVOICE#{session_id}", request_id=request_id,
            customer_id=session.get("customer_id"),
            action=f"voice.forbidden/{name}", decision="deny",
            reason="the voice surface has no settlement authority",
            policy_version=policy.VERSION, result_status="blocked",
        )
        return _resp(200, {"status": "not_permitted", "result": None,
                           "error": "This assistant cannot approve or settle claims. "
                                    "A claims specialist makes that decision."})

    if name not in claims_voice.REGISTRY:
        return _resp(200, {"status": "error", "result": None,
                           "error": f"unknown tool: {name}"})

    invalid = claims_voice.validate_arguments(name, args)
    if invalid:
        return _resp(200, {"status": "invalid_request", "result": None,
                           "error": f"invalid arguments: {invalid}"})

    ctx = {"session_id": session_id, "request_id": request_id,
           "customer_id": session.get("customer_id")}

    started = time.time()
    try:
        result = claims_voice.REGISTRY[name](args, ctx)
    except Exception:  # noqa: BLE001
        log.exception("claims voice tool %s failed", name)
        result = {"status": "error", "result": None,
                  "error": "That information is not available right now."}
    latency_ms = int((time.time() - started) * 1000)

    log.info(json.dumps({
        "event": "claim_voice_tool", "request_id": request_id,
        "session_id": session_id, "customer_id": session.get("customer_id"),
        "tool": name, "status": result.get("status"), "latency_ms": latency_ms,
        "argument_names": sorted(args.keys()) if isinstance(args, dict) else [],
    }))
    try:
        store.bump_tool_counter(f"voice.{name}", result.get("status", "unknown"))
    except Exception:  # noqa: BLE001
        log.warning("voice tool counter increment failed", exc_info=False)

    return _resp(200, {**result, "latency_ms": latency_ms})


def handle_claim_voice_event(event):
    """
    Client telemetry. Timings and lifecycle only — never transcript content.

    Time to first audio and barge-in are observable in the browser and nowhere
    else, so the client reports them and the server records them.
    """
    claims = _claims(event)
    sub = claims.get("sub")
    if not sub:
        return _resp(401, {"error": "authentication required"})

    try:
        body = json.loads(event.get("body") or "{}")
    except json.JSONDecodeError:
        return _resp(400, {"error": "malformed request"})

    allowed = {"session_connected", "first_assistant_audio", "interruption",
               "session_ended", "connection_failed", "reconnect_attempt",
               # Diagnostic: which Realtime event types the browser actually
               # received, and which path ended each turn. The Realtime event
               # stream runs browser-to-OpenAI over WebRTC and never reaches
               # CloudWatch, so without this the server is blind to it.
               "realtime_events"}
    name = body.get("event")
    if name not in allowed:
        return _resp(400, {"error": "unrecognised event"})

    session_id = body.get("session_id")
    session = store.get_session(session_id) if session_id else None
    if not session or session.get("cognito_sub") != sub:
        return _resp(403, {"error": "not your session"})

    def _num(key):
        value = body.get(key)
        return int(value) if isinstance(value, (int, float)) else None

    log.info(json.dumps({
        "event": f"claim_voice_{name}",
        "session_id": session_id,
        "customer_id": session.get("customer_id"),
        "ms_to_first_audio": _num("ms_to_first_audio"),
        "session_duration_ms": _num("session_duration_ms"),
        "turn": _num("turn"),
        "detail": str(body.get("detail"))[:120] if body.get("detail") else None,
        # Diagnostic payloads. Event type names and commit-path counters only —
        # no transcript text, so this stays free of claim content.
        "realtime_event_types": str(body.get("event_types"))[:800]
                                if body.get("event_types") else None,
        "commit_paths": str(body.get("commit_paths"))[:200]
                        if body.get("commit_paths") else None,
    }))
    return _resp(200, {"recorded": True})


