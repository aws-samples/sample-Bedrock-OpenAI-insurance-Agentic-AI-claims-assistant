def handle_usage_summary(event):
    claims = _claims(event)
    if not claims.get("sub"):
        return _resp(401, {"error": "authentication required"})

    body = json.loads(event.get("body") or "{}")
    session_id = body.get("session_id")

    def clean(item):
        return {k: (int(v) if isinstance(v, Decimal) else v)
                for k, v in (item or {}).items()
                if k not in ("pk", "sk")}

    payload = {
        "model": MODEL,
        "global": clean(store.usage_global()),
        "tools": clean(store.usage_tools()),
        "sessions": [clean(i) for i in store.usage_sessions()],
    }
    if session_id:
        payload["turns"] = [clean(i) for i in store.usage_turns(session_id)]
    return _resp(200, payload)


