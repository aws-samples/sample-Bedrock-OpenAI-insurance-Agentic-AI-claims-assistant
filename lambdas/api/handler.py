def handle_claim_analyze(event):
    claims_ = _claims(event)
    sub = claims_.get("sub")
    username = claims_.get("cognito:username") or claims_.get("username")
    if not sub or not username:
        return _resp(401, {"error": "authentication required"})

    import claims as copilot
    import claims_data

    request_id = event["requestContext"]["requestId"]
    started = time.time()
    try:
        result, meta = copilot.call_model(SECRET_ARN)
    except urllib.error.HTTPError as exc:
        detail = _safe_upstream_detail(exc.read(), limit=300)
        log.error("claims model call rejected upstream: status=%s detail=%s", exc.code, detail)
        return _resp(502, {"error": "the assistant is unavailable",
                           "upstream_status": exc.code})
    except Exception:  # noqa: BLE001
        log.exception("claims analyze failed")
        return _resp(502, {"error": "the assistant is unavailable"})

    checks, blocking = copilot.validate(result)
    passed = sum(1 for c in checks if c["ok"])

    # Every rupee figure in the response comes from here, not from the model.
    settlement = copilot.settlement_estimate()

    review_id = f"REV-{request_id[-8:].upper()}"
    store.put_holding(username, f"CLAIMREV#{review_id}", {
        "review_id": review_id,
        "claim_id": claims_data.CLAIM["claim_id"],
        "specialist": username,
        "model": meta["model"],
        "status": result.get("status"),
        "recommended_action": result.get("recommended_action"),
        "checks_passed": passed,
        "checks_total": len(checks),
        "blocking": blocking,
        "decision": "pending",
        "created_at": int(time.time()),
        "latency_ms": meta["latency_ms"],
        "input_tokens": meta["input_tokens"],
        "output_tokens": meta["output_tokens"],
        "payable_if_complete": settlement["payable_if_complete"],
        "value_of_the_query": settlement["value_of_the_query"],
    })

    log.info(json.dumps({
        "event": "claim_review", "request_id": request_id, "review_id": review_id,
        "specialist": username, "claim_id": claims_data.CLAIM["claim_id"],
        "model": meta["model"], "status": result.get("status"),
        "recommended_action": result.get("recommended_action"),
        "checks_passed": passed, "checks_total": len(checks), "blocking": blocking,
        "latency_ms": meta["latency_ms"],
        "input_tokens": meta["input_tokens"], "output_tokens": meta["output_tokens"],
        "reasoning_tokens": meta["reasoning_tokens"],
        "evidence_sources": [e.get("source_id") for e in (result.get("evidence") or [])],
        "deductions_flagged": [d.get("basis_source_id") for d
                               in (result.get("deductions_applicable") or [])
                               if d.get("applies")],
        "payable_if_complete": settlement["payable_if_complete"],
        "value_of_the_query": settlement["value_of_the_query"],
    }))

    return _resp(200, {
        "review_id": review_id,
        "claim_id": claims_data.CLAIM["claim_id"],
        "recommendation": result,
        "settlement": settlement,
        "validation": {"checks": checks, "passed": passed,
                       "total": len(checks), "blocking": blocking},
        "meta": meta,
        "governance": {
            "model_may_settle": False,
            "model_may_state_an_amount": False,
            "requires_human_decision": True,
            "note": "The assistant recommends and never states a figure. Every "
                    "rupee amount is computed by the claims system. Nothing is "
                    "sent or settled without an explicit specialist decision.",
        },
    })


def handle_claim_decision(event):
    """
    The human gate. This is the only call that produces a business outcome, and
    the model has no route to it.
    """
    claims_ = _claims(event)
    sub = claims_.get("sub")
    username = claims_.get("cognito:username") or claims_.get("username")
    if not sub or not username:
        return _resp(401, {"error": "authentication required"})

    body = json.loads(event.get("body") or "{}")
    review_id = body.get("review_id")
    decision = (body.get("decision") or "").lower()
    if decision not in ("approve", "edit", "reject"):
        return _resp(400, {"error": "decision must be approve, edit or reject"})
    if not review_id:
        return _resp(400, {"error": "review_id required"})

    review = store._get(f"CUSTOMER#{username}", f"CLAIMREV#{review_id}")
    if not review:
        return _resp(404, {"error": "no such review on this profile"})
    if review.get("blocking"):
        return _resp(409, {"error": "this recommendation failed a blocking "
                                    "validation check and cannot be approved"})

    request_id = event["requestContext"]["requestId"]
    outcome = {"approve": "QUERY_SENT_TO_HOSPITAL", "edit": "EDITED_THEN_SENT",
               "reject": "DISCARDED"}[decision]
    edited = body.get("edited_message") if decision == "edit" else None

    store.put_holding(username, f"CLAIMREV#{review_id}", {
        **{k: v for k, v in review.items() if k not in ("pk", "sk")},
        "decision": decision,
        "outcome": outcome,
        "decided_by": username,
        "decided_at": int(time.time()),
        "edited": bool(edited),
    })

    audit.append(
        f"CLAIMS#{review_id}",
        request_id=request_id, customer_id=username,
        action=f"claim.{decision}", decision="allow",
        reason=f"specialist {decision} on {review.get('claim_id')}",
        policy_version=policy.VERSION, result_status=outcome,
        extra={"review_id": review_id, "model": review.get("model"),
               "recommended_action": review.get("recommended_action")},
    )

    log.info(json.dumps({
        "event": "claim_decision", "request_id": request_id, "review_id": review_id,
        "specialist": username, "decision": decision, "outcome": outcome,
        "edited": bool(edited), "claim_id": review.get("claim_id"),
    }))

    return _resp(200, {
        "review_id": review_id, "decision": decision, "outcome": outcome,
        "decided_by": username, "audit_chain": f"CLAIMS#{review_id}",
        "note": "Recorded. In production this is the point at which the query is "
                "released to the hospital and the TPA claims system of record is "
                "written, under the specialist's identity.",
    })


