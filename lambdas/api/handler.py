# ── POST /usage ───────────────────────────────────────────────────────
def _flatten_usage(u):
    """Normalise the Realtime usage object into flat counters."""
    ind = u.get("input_token_details") or {}
    outd = u.get("output_token_details") or {}
    cached = ind.get("cached_tokens_details") or {}

    c_text = int(cached.get("text_tokens", 0) or 0)
    c_audio = int(cached.get("audio_tokens", 0) or 0)
    if not (c_text or c_audio):
        # Older payloads report a single cached_tokens figure.
        c_text = int(ind.get("cached_tokens", 0) or 0)

    in_text = max(int(ind.get("text_tokens", 0) or 0) - c_text, 0)
    in_audio = max(int(ind.get("audio_tokens", 0) or 0) - c_audio, 0)

    return {
        "in_text": in_text,
        "in_audio": in_audio,
        "in_cached_text": c_text,
        "in_cached_audio": c_audio,
        "out_text": int(outd.get("text_tokens", 0) or 0),
        "out_audio": int(outd.get("audio_tokens", 0) or 0),
        "total_tokens": int(u.get("total_tokens", 0) or 0),
    }


def handle_usage(event):
    claims = _claims(event)
    sub = claims.get("sub")
    if not sub:
        return _resp(401, {"error": "authentication required"})

    body = json.loads(event.get("body") or "{}")
    session_id = body.get("session_id")
    usage = body.get("usage") or {}
    if not session_id or not isinstance(usage, dict):
        return _resp(400, {"error": "session_id and usage required"})

    session = store.get_session(session_id)
    if not session or session.get("cognito_sub") != sub:
        return _resp(403, {"error": "not your session"})

    flat = _flatten_usage(usage)
    if flat["total_tokens"] == 0:
        flat["total_tokens"] = sum(flat[k] for k in flat if k != "total_tokens")

    turn = int(body.get("turn") or 0)
    store.record_usage(session_id, session["customer_id"], turn, flat)

    log.info(json.dumps({"event": "usage", "session_id": session_id,
                         "turn": turn, **flat}))
    return _resp(200, {"recorded": True, **flat})


